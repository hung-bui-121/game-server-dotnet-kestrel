using System.Diagnostics;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using GameServer.Time;
using Microsoft.AspNetCore.OpenApi;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;
using Microsoft.OpenApi;

namespace GameServer.Platform.Web.OpenApi;

/// <summary>The canonical bytes of the GM document and their strong entity tag (<c>"</c> + 32 hex of SHA-256 + <c>"</c>).</summary>
public sealed record GmCatalogBytes(ReadOnlyMemory<byte> Bytes, string ETag);

/// <summary>
/// The canonical bytes of the host's GM document (slice 017, research R4/R8), generated once per process on first use (no
/// cost at host start, D12) and kept: served by the catalog route <c>gm.console_catalog</c> and written or compared by the test
/// kit's <c>GmOpenApiSnapshot</c>. Canonical = the OpenAPI 3.1 JSON re-written by System.Text.Json, indented, LF line ends,
/// one final newline, UTF-8 without BOM. A failed generation is kept for <see cref="FailureHold"/> (callers get the same
/// failure), then the next call generates again: a deterministic failure does not cost a generation per request.
/// </summary>
public sealed class GmCatalogDocument
{
    /// <summary>Log category of the one Information line per generation.</summary>
    public const string LogCategory = "GameServer.Gm.Catalog";

    /// <summary>How long a failed generation answers every caller before the next call retries (review r1 m5).</summary>
    public static readonly TimeSpan FailureHold = TimeSpan.FromSeconds(30);

    private const int ETagHexLength = 32;

    private static readonly JsonSerializerOptions Canonical = new() { WriteIndented = true, NewLine = "\n" };

    private readonly Func<CancellationToken, Task<(string Json, int Operations)>> _generate;
    private readonly ILogger _logger;
    private readonly IClock _clock;
    private readonly Lock _gate = new();
    private Task<GmCatalogBytes>? _current;
    private DateTimeOffset _failedAt;

    public GmCatalogDocument(IServiceProvider services, ILoggerFactory loggerFactory, IClock clock)
        : this(cancellationToken => FromProviderAsync(services, cancellationToken), loggerFactory, clock)
    {
    }

    /// <summary>Test seam: <paramref name="generate"/> returns the OpenAPI JSON and its operation count.</summary>
    internal GmCatalogDocument(Func<CancellationToken, Task<(string Json, int Operations)>> generate, ILoggerFactory loggerFactory, IClock clock)
    {
        ArgumentNullException.ThrowIfNull(generate);
        ArgumentNullException.ThrowIfNull(loggerFactory);
        ArgumentNullException.ThrowIfNull(clock);
        _generate = generate;
        _logger = loggerFactory.CreateLogger(LogCategory);
        _clock = clock;
    }

    /// <summary>
    /// The bytes, generated by the first caller; concurrent first callers share one generation. Cancelling waits less, never the
    /// generation itself (other callers may wait on it).
    /// </summary>
    public Task<GmCatalogBytes> GetAsync(CancellationToken cancellationToken)
    {
        Task<GmCatalogBytes> current;
        lock (_gate)
        {
            var failed = _current is { IsFaulted: true } or { IsCanceled: true };
            if (_current is null || (failed && _clock.UtcNow - _failedAt >= FailureHold))
            {
                _current = Task.Run(GenerateAsync, CancellationToken.None);
            }

            current = _current;
        }

        return current.WaitAsync(cancellationToken);
    }

    /// <summary>The canonical text of an OpenAPI JSON document (shared with the snapshot comparison).</summary>
    internal static string Canonicalize(string openApiJson) =>
        (JsonNode.Parse(openApiJson) ?? throw new InvalidOperationException("The GM OpenAPI document is empty.")).ToJsonString(Canonical) + "\n";

    private async Task<GmCatalogBytes> GenerateAsync()
    {
        try
        {
            return await GenerateCoreAsync();
        }
        catch
        {
            // Read under the gate by GetAsync after it sees this task faulted (the task completes after this assignment).
            _failedAt = _clock.UtcNow;
            throw;
        }
    }

    private async Task<GmCatalogBytes> GenerateCoreAsync()
    {
        var started = Stopwatch.GetTimestamp();
        var (json, operations) = await _generate(CancellationToken.None);
        var bytes = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false).GetBytes(Canonicalize(json));
        var etag = "\"" + Convert.ToHexStringLower(SHA256.HashData(bytes))[..ETagHexLength] + "\"";
        _logger.LogInformation(
            "GM catalog generated: {Operations} operations, {Bytes} bytes, {ElapsedMs} ms.",
            operations,
            bytes.Length,
            (long)Stopwatch.GetElapsedTime(started).TotalMilliseconds);
        return new GmCatalogBytes(bytes, etag);
    }

    /// <summary>The document of the keyed provider (V11): generated from the endpoints, no HTTP request, no <c>servers</c>.</summary>
    private static async Task<(string Json, int Operations)> FromProviderAsync(IServiceProvider services, CancellationToken cancellationToken)
    {
        var provider = services.GetRequiredKeyedService<IOpenApiDocumentProvider>(GmOpenApi.DocumentName);
        var document = await provider.GetOpenApiDocumentAsync(cancellationToken);
        using var writer = new StringWriter(CultureInfo.InvariantCulture);
        document.SerializeAsV31(new OpenApiJsonWriter(writer));
        var operations = document.Paths?.Values.Sum(path => path.Operations?.Count ?? 0) ?? 0;
        return (writer.ToString(), operations);
    }
}
