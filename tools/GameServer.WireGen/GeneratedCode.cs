using System.Text;

namespace GameServer.WireGen;

/// <summary>
/// Text shared by the route and section files (contracts/generated-files.md §3–§4): the header naming the generator and the
/// framework version, and escaping. No timestamp, path, user or machine (FR-023); LF here, the writer applies the line ending.
/// </summary>
internal static class GeneratedCode
{
    public const string Indent = "    ";

    public static void AppendHeader(StringBuilder text, string frameworkVersion) =>
        text.Append("// <auto-generated>\n")
            .Append("//   Generated by GameServer.WireGen (framework ").Append(frameworkVersion).Append(") from the server's route catalog. Do not edit:\n")
            .Append("//   change the route declaration on the server and run the generation step again.\n")
            .Append("// </auto-generated>\n")
            .Append("#nullable enable\n")
            .Append('\n');

    /// <summary>A C# regular string literal.</summary>
    public static string Literal(string value) =>
        "\"" + value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";

    /// <summary>Text inside an XML doc comment.</summary>
    public static string Xml(string value) =>
        value.Replace("&", "&amp;", StringComparison.Ordinal).Replace("<", "&lt;", StringComparison.Ordinal).Replace(">", "&gt;", StringComparison.Ordinal);

    /// <summary>"the framework" or "the game", for the class summaries.</summary>
    public static string Of(string origin) => origin == "framework" ? "the framework" : "the game";
}

/// <summary>Member names of one generated class must be unique (data-model §5): the first source of each name is kept.</summary>
internal sealed class MemberNames(string className)
{
    private readonly Dictionary<string, string> _sources = new(StringComparer.Ordinal);
    private readonly List<string> _errors = [];

    public void Add(string member, string source)
    {
        if (member == className)
        {
            _errors.Add($"{source} generates the member {member}, the name of its class. Fix: rename it or choose another class name in wiregen.json.");
        }
        else if (!_sources.TryAdd(member, source))
        {
            _errors.Add($"{_sources[member]} and {source} both generate the member {className}.{member}. Fix: rename one of them (FG-026).");
        }
    }

    public void ThrowIfAny()
    {
        if (_errors.Count > 0)
        {
            throw new WireGenException(_errors);
        }
    }
}
