using Google.Protobuf.Reflection;

namespace GameServer.WireGen;

/// <summary>A proto message with the file declaring it and the C# type protoc generates for it (V8).</summary>
/// <param name="FullName">Proto full name, e.g. <c>fixture.v1.CardState.Inner</c>.</param>
/// <param name="File">Virtual (import-root relative) name of the declaring file.</param>
/// <param name="CSharpName">C# full name without <c>global::</c>, e.g. <c>Fixture.V1.CardState.Types.Inner</c>.</param>
internal sealed record ProtoMessage(string FullName, string File, string CSharpName);

/// <summary>
/// Messages of the descriptor pass (research R11, contracts/wiregen-cli.md §4 steps 6–8): full name → file and C# type (namespace
/// = <c>csharp_namespace</c>, else protoc's package rule; class = message name; nested <c>Outer.Types.Inner</c>). Knows which files
/// the run generates (consumer) and which come from the framework (Unity package, Google.Protobuf well-known types).
/// </summary>
internal sealed class ProtoModel
{
    private const string WellKnownPrefix = "google/protobuf/";

    private readonly Dictionary<string, ProtoMessage> _messages = new(StringComparer.Ordinal);
    private readonly HashSet<string> _consumerFiles;
    private readonly HashSet<string> _frameworkFiles;

    private ProtoModel(IEnumerable<string> consumerFiles, IEnumerable<string> frameworkFiles)
    {
        _consumerFiles = new HashSet<string>(consumerFiles, StringComparer.Ordinal);
        _frameworkFiles = new HashSet<string>(frameworkFiles, StringComparer.Ordinal);
    }

    public IReadOnlyCollection<ProtoMessage> Messages => _messages.Values;

    public static ProtoModel Build(FileDescriptorSet set, IEnumerable<string> consumerFiles, IEnumerable<string> frameworkFiles)
    {
        ArgumentNullException.ThrowIfNull(set);
        var model = new ProtoModel(consumerFiles, frameworkFiles);
        foreach (var file in set.File)
        {
            var ns = file.Options?.HasCsharpNamespace == true ? file.Options.CsharpNamespace : Names.ProtocNamespace(file.Package);
            var protoPrefix = file.Package.Length > 0 ? file.Package + "." : string.Empty;
            var csharpPrefix = ns.Length > 0 ? ns + "." : string.Empty;
            foreach (var message in file.MessageType)
            {
                model.Add(file.Name, message, protoPrefix, csharpPrefix);
            }
        }

        return model;
    }

    /// <summary>A message whose C# type exists on the client: generated by this run or shipped by the framework.</summary>
    public bool TryGetClientMessage(string fullName, out ProtoMessage message) =>
        _messages.TryGetValue(fullName, out message!) && (IsConsumer(message.File) || IsFramework(message.File));

    public bool IsConsumer(string file) => _consumerFiles.Contains(file);

    /// <summary>
    /// FR-021: a C# type generated by this run must not exist twice in the Unity project (a framework or well-known type, or another
    /// generated file). protoc accepts different packages with the same <c>csharp_namespace</c> and message name.
    /// </summary>
    public IReadOnlyList<string> Clashes()
    {
        var errors = new List<string>();
        foreach (var group in _messages.Values.GroupBy(m => m.CSharpName, StringComparer.Ordinal).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            var messages = group.OrderBy(m => IsConsumer(m.File) ? 1 : 0).ThenBy(m => m.FullName, StringComparer.Ordinal).ToArray();
            var generated = messages.Where(m => IsConsumer(m.File)).ToArray();
            if (messages.Length < 2 || generated.Length == 0)
            {
                continue;
            }

            var other = messages.First(m => m != generated[0]);
            errors.Add($"[proto] message {generated[0].FullName} ({generated[0].File}) and message {other.FullName} ({other.File}) both become the C# type " +
                $"{group.Key}. Fix: rename the game message or give its file another csharp_namespace (FR-021).");
        }

        return errors;
    }

    private bool IsFramework(string file) => _frameworkFiles.Contains(file) || file.StartsWith(WellKnownPrefix, StringComparison.Ordinal);

    private void Add(string file, DescriptorProto message, string protoPrefix, string csharpPrefix)
    {
        if (message.Options?.MapEntry == true)
        {
            // A map field's synthetic entry message has no C# type.
            return;
        }

        var fullName = protoPrefix + message.Name;
        var csharpName = csharpPrefix + message.Name;
        _messages.TryAdd(fullName, new ProtoMessage(fullName, file, csharpName));
        foreach (var nested in message.NestedType)
        {
            Add(file, nested, fullName + ".", csharpName + ".Types.");
        }
    }
}
