using System.Runtime.InteropServices;
using Google.Protobuf.Reflection;

namespace GameServer.WireGen;

/// <summary>A proto file under its import root; <see cref="Relative"/> is protoc's virtual name (<c>/</c>-separated).</summary>
internal sealed record ProtoFile(string Root, string Relative)
{
    public string FullPath => Path.GetFullPath(Path.Combine(Root, Relative));
}

/// <summary>The C# protoc wrote for one proto: its path relative to <c>output.directory</c> (layout applied) and its text.</summary>
internal sealed record GeneratedFile(string RelativePath, string Text);

/// <summary>
/// The framework-pinned protoc (FR-021, FR-022, research R11, V6, V7): located under the tool's own restored <c>Grpc.Tools</c>
/// (<c>tools/&lt;os&gt;_&lt;arch&gt;/</c>; every macOS architecture uses <c>macosx_universal</c>), Unix execute bit set when
/// missing. The framework import roots (<c>proto/</c>, the identity, economy and IAP <c>Protos</c> folders, the well-known types)
/// are always added; framework protos are descriptor-pass inputs and import roots only, never generated by a game run.
/// </summary>
internal sealed class Protoc
{
    private static readonly TimeSpan RunTimeout = TimeSpan.FromMinutes(2);

    private static readonly string[] FrameworkRootPaths =
    [
        "proto",
        "src/GameServer.Modules.Identity.Adapters/Protos",
        "src/GameServer.Modules.Economy.Adapters/Protos",
        "src/GameServer.Modules.Iap.Adapters/Protos",
    ];

    private Protoc(string executable, IReadOnlyList<string> frameworkRoots, string includeRoot)
    {
        Executable = executable;
        FrameworkRoots = frameworkRoots;
        IncludeRoot = includeRoot;
    }

    public string Executable { get; }

    public IReadOnlyList<string> FrameworkRoots { get; }

    /// <summary><c>Grpc.Tools</c> <c>build/native/include</c>: the well-known types (<c>google/protobuf/*.proto</c>).</summary>
    public string IncludeRoot { get; }

    public static Protoc Locate(ToolInfo tool)
    {
        var folder = PlatformFolder();
        var executable = Path.Combine(tool.GrpcToolsRoot, "tools", folder, OperatingSystem.IsWindows() ? "protoc.exe" : "protoc");
        if (!File.Exists(executable))
        {
            throw new WireGenException($"[protoc] {executable} does not exist (Grpc.Tools {tool.GrpcToolsVersion}). Fix: restore the framework " +
                "(dotnet restore tools/GameServer.WireGen) and run the tool from that checkout.");
        }

        if (!OperatingSystem.IsWindows())
        {
            // NuGet extracts without the execute bit (V6).
            const UnixFileMode execute = UnixFileMode.UserExecute | UnixFileMode.GroupExecute | UnixFileMode.OtherExecute;
            var mode = File.GetUnixFileMode(executable);
            if ((mode & UnixFileMode.UserExecute) == 0)
            {
                File.SetUnixFileMode(executable, mode | execute);
            }
        }

        var roots = FrameworkRootPaths.Select(r => Path.GetFullPath(Path.Combine(tool.FrameworkRoot, r))).ToArray();
        return new Protoc(executable, roots, Path.GetFullPath(Path.Combine(tool.GrpcToolsRoot, "build", "native", "include")));
    }

    /// <summary>Every <c>.proto</c> under the framework roots, ordinal by virtual name.</summary>
    public IReadOnlyList<ProtoFile> FrameworkProtos() =>
        FrameworkRoots
            .Where(Directory.Exists)
            .SelectMany(root => Directory.EnumerateFiles(root, "*.proto", SearchOption.AllDirectories)
                .Select(file => new ProtoFile(root, Path.GetRelativePath(root, file).Replace('\\', '/'))))
            .OrderBy(p => p.Relative, StringComparer.Ordinal)
            .ToArray();

    /// <summary>The <c>-I</c> roots of a run: consumer roots first (config order), then the framework roots and the well-known types.</summary>
    public IReadOnlyList<string> ImportRoots(IEnumerable<string> consumerRoots) =>
        consumerRoots.Concat(FrameworkRoots).Append(IncludeRoot).Distinct(PathComparer).ToArray();

    /// <summary>Descriptor pass (step 6): protoc fails on duplicate symbols ("already defined") before anything is written.</summary>
    public async Task<FileDescriptorSet> DescribeAsync(IReadOnlyList<string> importRoots, IEnumerable<ProtoFile> files, string tempFolder)
    {
        var output = Path.Combine(tempFolder, "descriptor-set.pb");
        var arguments = Includes(importRoots).Append($"--descriptor_set_out={output}").Append("--include_imports")
            .Concat(files.Select(f => f.FullPath).Distinct(PathComparer))
            .ToArray();
        await RunAsync(arguments, tempFolder, "descriptor pass");
        return FileDescriptorSet.Parser.ParseFrom(await File.ReadAllBytesAsync(output));
    }

    /// <summary>C# pass (step 9) for one consumer proto, no gRPC plugin, into a fresh folder: exactly one <c>.cs</c> is expected.</summary>
    public async Task<GeneratedFile> GenerateCSharpAsync(IReadOnlyList<string> importRoots, ProtoFile proto, OutputLayout layout, string tempFolder)
    {
        var output = Directory.CreateDirectory(Path.Combine(tempFolder, "cs-" + Guid.NewGuid().ToString("N"))).FullName;
        await RunAsync([.. Includes(importRoots), $"--csharp_out={output}", proto.FullPath], tempFolder, proto.Relative);
        var written = Directory.GetFiles(output, "*.cs", SearchOption.AllDirectories);
        if (written.Length != 1)
        {
            throw new WireGenException(
                $"[protoc] expected output for {proto.Relative} missing: protoc wrote {written.Length} C# files instead of one. Fix: check the proto " +
                "(FR-024).");
        }

        var name = Path.GetFileName(written[0]);
        var folder = layout == OutputLayout.ByRoot ? Path.GetDirectoryName(proto.Relative)?.Replace('\\', '/') : null;
        var relative = string.IsNullOrEmpty(folder) ? name : folder + "/" + name;
        return new GeneratedFile(relative, await File.ReadAllTextAsync(written[0]));
    }

    private static StringComparer PathComparer => OperatingSystem.IsWindows() ? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal;

    private static IEnumerable<string> Includes(IEnumerable<string> roots) => roots.Select(root => "-I" + root);

    private async Task RunAsync(IReadOnlyList<string> arguments, string workingDirectory, string what)
    {
        var result = await ChildProcess.RunAsync(Executable, arguments, workingDirectory, RunTimeout);
        if (result.ExitCode != 0)
        {
            throw new WireGenException(
                new[] { $"[protoc] {what} failed (exit code {result.ExitCode}):" }
                    .Concat(result.FailureLines().Select(line => "  " + line))
                    .Append("Fix: correct the proto as protoc says (FR-025).")
                    .ToArray());
        }
    }

    private static string PlatformFolder()
    {
        if (OperatingSystem.IsMacOS())
        {
            return "macosx_universal";
        }

        var os = OperatingSystem.IsWindows() ? "windows" : OperatingSystem.IsLinux() ? "linux" : null;
        var arch = RuntimeInformation.OSArchitecture switch
        {
            Architecture.X64 => "x64",
            Architecture.X86 => "x86",

            // Grpc.Tools ships no windows_arm64 protoc; Windows on Arm runs the x64 one.
            Architecture.Arm64 when OperatingSystem.IsWindows() => "x64",
            Architecture.Arm64 => "arm64",
            _ => null,
        };
        return os is not null && arch is not null
            ? $"{os}_{arch}"
            : throw new WireGenException($"[protoc] Grpc.Tools has no protoc for {RuntimeInformation.OSDescription} {RuntimeInformation.OSArchitecture}.");
    }
}
